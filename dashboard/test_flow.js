'use strict';
const assert=require('node:assert/strict');
const flow=require('./flow.js');
const wallets={A:'0x1111111111111111111111111111111111111111',B:'0x2222222222222222222222222222222222222222'};
const elements=new Map();
const doc={getElementById(id){if(!elements.has(id))elements.set(id,{textContent:'',title:'',dataset:{},classList:{add(){},remove(){}}});return elements.get(id);}};
const tx={from:wallets.A,to:wallets.B,amount:'1.000000000000000001',hash:'0xtest'};
assert.equal(flow.receiptState({status:'pending'}),'pending');
assert.equal(flow.receiptState({status:'confirmed'}),'pending');
assert.equal(flow.receiptState({status:'unknown'}),'pending');
flow.render(doc,tx,{status:'pending'},wallets);
assert.equal(doc.getElementById('flow').dataset.status,'pending');
assert.match(doc.getElementById('flowStatus').textContent,/awaiting confirmation/);
flow.render(doc,tx,{status:'confirmed',block:1652,gasUsed:35082},wallets);
assert.equal(doc.getElementById('flow').dataset.status,'confirmed');
assert.equal(doc.getElementById('flowStatus').textContent,'1.000000000000000001 AST confirmed');
assert.equal(doc.getElementById('flowFrom').textContent,'Wallet A');
assert.equal(doc.getElementById('flowTo').textContent,'Wallet B');
flow.render(doc,{...tx,from:wallets.B,to:wallets.A},{status:'confirmed',block:1653,gasUsed:35082},wallets,true);
assert.equal(doc.getElementById('flowFrom').textContent,'Wallet B');
assert.match(doc.getElementById('flowStatus').textContent,/^Replay/);
flow.render(doc,tx,{status:'reverted',block:1654},wallets);
assert.equal(doc.getElementById('flow').dataset.status,'reverted');
assert.match(doc.getElementById('flowStatus').textContent,/not delivered/);
assert.equal(flow.endpoint('0x0000000000000000000000000000000000000000',wallets).title,'Token mint');
assert.equal(flow.endpoint('0x3333333333333333333333333333333333333333',wallets).title,'Address');
console.log('Flow checks passed: pending, confirmed, reverted, replay, reverse direction, exact amounts, mint, external recipient. No RPC or signing calls.');
